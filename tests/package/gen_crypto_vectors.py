"""Generates crypto_vectors.inc: reference output of independent implementations (hashlib/hmac, the
`cryptography` package) for the primitives in engine/package/src/crypto.cpp.
Inputs are deterministic byte patterns: pat(n, salt)[i] = (i*7 + 3 + salt*31) & 0xFF."""
import hashlib, hmac
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives import hashes, poly1305

def pat(n, salt): return bytes(((i * 7 + 3 + salt * 31) & 0xFF) for i in range(n))
out = []
def emit(name, rows): out.append(f"static const {name}[] = {{\n" + "".join(rows) + "};\n")

emit("HashVec kSha", [f'    {{{n}, "{hashlib.sha256(pat(n, 1)).hexdigest()}"}},\n' for n in
      [0, 1, 3, 55, 56, 57, 63, 64, 65, 119, 120, 121, 127, 128, 129, 1000, 4096]])
emit("HmacVec kHmac", [f'    {{{k}, {d}, "{hmac.new(pat(k, 2), pat(d, 3), hashlib.sha256).hexdigest()}"}},\n'
      for k, d in [(0, 0), (1, 5), (20, 8), (32, 32), (64, 100), (65, 3), (131, 200), (200, 0)]])
def hk(ikm, salt, info, l):
    return HKDF(algorithm=hashes.SHA256(), length=l, salt=(salt if salt else None), info=info).derive(ikm)
emit("HkdfVec kHkdf", [f'    {{{a}, {b}, {c}, {l}, "{hk(pat(a, 4), pat(b, 5), pat(c, 6), l).hex()}"}},\n'
      for a, b, c, l in [(22, 13, 10, 42), (32, 16, 20, 32), (32, 0, 0, 64), (5, 7, 0, 100), (32, 32, 13, 255 * 32 if False else 8160)]])
emit("Pbkdf2Vec kPbkdf2", [f'    {{"{p}", {s}, {it}, {l}, "{hashlib.pbkdf2_hmac("sha256", p.encode(), pat(s, 7), it, l).hex()}"}},\n'
      for p, s, it, l in [("password", 4, 1, 32), ("password", 4, 2, 32), ("pässwörd", 16, 1000, 48), ("", 8, 3, 20), ("x" * 100, 16, 5, 64)]])
def cc(key, nonce, ctr, n):
    full = nonce.rjust(16, b"\0")
    c = Cipher(algorithms.ChaCha20(key, ctr.to_bytes(4, "little") + nonce), mode=None).encryptor()
    return c.update(bytes(n))
emit("ChaChaVec kChaCha", [f'    {{{c}, {n}, "{cc(pat(32, 8), pat(12, 9), c, n).hex()}"}},\n' for c, n in
      [(0, 64), (1, 64), (1, 200), (7, 1), (0, 130), (0xFFFFFFF0, 64)]])
def poly(key, data):
    return poly1305.Poly1305.generate_tag(key, data)
emit("PolyVec kPoly", [f'    {{{n}, "{poly(pat(32, 10), pat(n, 11)).hex()}"}},\n' for n in [0, 1, 15, 16, 17, 31, 32, 33, 64, 100, 1000]])
rows = []
for i, (a, p) in enumerate([(0, 0), (0, 1), (1, 0), (12, 15), (16, 16), (20, 17), (3, 64), (33, 100), (0, 1000), (100, 0), (7, 4096)]):
    key, nonce, aad, pt = pat(32, 20 + i), pat(12, 40 + i), pat(a, 60 + i), pat(p, 80 + i)
    ct = ChaCha20Poly1305(key).encrypt(nonce, pt, aad)
    rows.append(f'    {{{i}, {a}, {p}, "{ct.hex()}"}},\n')
emit("AeadVec kAead", rows)
open("crypto_vectors.inc", "w").write("// Generated by gen_crypto_vectors.py - do not edit.\n" + "".join(out))
