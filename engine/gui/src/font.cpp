const std::vector<std::uint8_t>& atlas() {
  static const std::vector<std::uint8_t> data = [] {
    std::vector<std::uint8_t> a(static_cast<std::size_t>(kAtlasW) * kAtlasH, 0);
    for (int cell = 0; cell <= kLast - kFirst + 1; ++cell) {
      const std::uint8_t* cols = cell == 0 ? kBox : kGlyphs[cell - 1];
      const int cx = (cell % kAtlasCols) * kCellW;
      const int cy = (cell / kAtlasCols) * kCellH;
      for (int c = 0; c < kGlyphW; ++c)
        for (int r = 0; r < kGlyphH; ++r)
          if ((cols[c] >> r) & 1) a[static_cast<std::size_t>(cy + r) * kAtlasW + (cx + c)] = 255;
    }
    return a;
  }();
  return data;
}

int cellFor(char32_t cp) {
  if (cp < static_cast<char32_t>(kFirst) || cp > static_cast<char32_t>(kLast)) return 0;
  return static_cast<int>(cp) - kFirst + 1;
}

std::vector<char32_t> decode(std::string_view s) {
  std::vector<char32_t> out;
  out.reserve(s.size());
  std::size_t i = 0;
  while (i < s.size()) {
    const auto b0 = static_cast<unsigned char>(s[i]);
    int len = 0;
    char32_t cp = 0;
    if (b0 < 0x80) { len = 1; cp = b0; }
    else if ((b0 & 0xE0) == 0xC0) { len = 2; cp = b0 & 0x1F; }
    else if ((b0 & 0xF0) == 0xE0) { len = 3; cp = b0 & 0x0F; }
    else if ((b0 & 0xF8) == 0xF0) { len = 4; cp = b0 & 0x07; }
    bool ok = len > 0 && i + static_cast<std::size_t>(len) <= s.size();
    for (int k = 1; ok && k < len; ++k) {
      const auto b = static_cast<unsigned char>(s[i + static_cast<std::size_t>(k)]);
      if ((b & 0xC0) != 0x80) ok = false; else cp = (cp << 6) | (b & 0x3F);
    }
    // Reject overlong forms, surrogates and out-of-range values.
    if (ok && ((len == 2 && cp < 0x80) || (len == 3 && cp < 0x800) || (len == 4 && cp < 0x10000) ||
               (cp >= 0xD800 && cp <= 0xDFFF) || cp > 0x10FFFF))
      ok = false;
    if (ok) { out.push_back(cp); i += static_cast<std::size_t>(len); }
    else { out.push_back(0xFFFD); ++i; }
  }
  return out;
}

